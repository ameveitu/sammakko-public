"""Headless Blender: a soft, sculpted-looking island for the /saaristo/ experiment page.

Run from the repository root:
  /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup -P tools/saaristo/blender/island.py -- \
      --out tools/saaristo/src/island-mesh.js [--seed 20261104]

Builds a subdivided disc, raises it with layered noise (sculpt-like "inflate + smooth" passes),
adds a few boulders, paints vertex colours by height and slope (sand, grass, moss, rock) and writes
a compact JS module (quantised positions, normals, colours, indices as base64) that the page bundles.
No textures, no characters.
"""
import argparse
import base64
import math
import random
import struct
import sys

import bpy
import bmesh
from mathutils import Vector, noise

argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
ap = argparse.ArgumentParser()
ap.add_argument('--out', required=True)
ap.add_argument('--seed', type=int, default=20261104)
args = ap.parse_args(argv)
rng = random.Random(args.seed)
noise.seed_set(args.seed) if hasattr(noise, 'seed_set') else None

for obj in list(bpy.data.objects):
    bpy.data.objects.remove(obj, do_unlink=True)

R = 10.0  # island radius in metres (page scales it)
bm = bmesh.new()
bmesh.ops.create_circle(bm, cap_ends=True, cap_tris=False, segments=96, radius=R * 1.25)
bmesh.ops.triangulate(bm, faces=bm.faces[:])
for _ in range(3):
    bmesh.ops.subdivide_edges(bm, edges=bm.edges[:], cuts=1, use_grid_fill=True)
bmesh.ops.triangulate(bm, faces=bm.faces[:])
off = Vector((rng.uniform(0, 50), rng.uniform(0, 50), 0))


def height(x, y):
    p = Vector((x, y, 0)) / R
    # Irregular coastline: warp the radius with low-frequency noise.
    ang = math.atan2(y, x)
    coast = 0.82 + 0.16 * noise.noise(Vector((math.cos(ang) * 1.3, math.sin(ang) * 1.3, 0)) + off)
    d = p.length / coast
    dome = max(0.0, 1.0 - d * d) ** 1.4
    hill = 0.55 * max(0.0, 1.0 - ((p - Vector((-0.22, 0.18, 0))).length / 0.5) ** 2) ** 2
    detail = 0.08 * noise.fractal(p * 3.0 + off, 0.6, 2.0, 4)
    h = dome * (2.2 + hill * 2.6) + detail * dome
    return h - 0.35 * max(0.0, d - 0.95) * 3.0  # shelf dips under water


def headland(x, y):
    # Stretch the east side into a long, slightly curving point that runs off the right edge.
    s = max(0.0, min(1.0, x / (R * 1.25))) ** 1.5
    return x * (1 + 1.6 * s), y * (1 - 0.45 * s) - 2.6 * s * s


for v in bm.verts:
    v.co.z = height(v.co.x, v.co.y)
    v.co.x, v.co.y = headland(v.co.x, v.co.y)
# Sculpt-style smoothing passes.
for _ in range(3):
    bmesh.ops.smooth_vert(bm, verts=bm.verts[:], factor=0.5, use_axis_x=False, use_axis_y=False, use_axis_z=True)
bm.normal_update()

# Boulders: squashed icospheres merged into the same mesh.
for _ in range(7):
    ang = rng.uniform(0, math.tau)
    rad = rng.uniform(0.55, 0.85) * R
    x, y = math.cos(ang) * rad, math.sin(ang) * rad
    s = rng.uniform(0.35, 0.8)
    ret = bmesh.ops.create_icosphere(bm, subdivisions=2, radius=s)
    hx, hy = headland(x, y)
    for v in ret['verts']:
        jitter = 1 + 0.18 * noise.noise(v.co * 2.5 + off)
        v.co = Vector((v.co.x * jitter * 1.3, v.co.y * jitter, v.co.z * 0.6 * jitter)) + Vector((hx, hy, height(x, y) - 0.1))
bm.normal_update()

positions, normals, colors, indices = [], [], [], []
SAND, GRASS, MOSS, ROCK = (0.91, 0.82, 0.6), (0.55, 0.69, 0.39), (0.36, 0.53, 0.33), (0.55, 0.57, 0.55)


def mix(a, b, t):
    t = max(0.0, min(1.0, t))
    return tuple(a[i] * (1 - t) + b[i] * t for i in range(3))


vid = {}
bm.verts.ensure_lookup_table()
for f in bm.faces:
    for v in f.verts:
        if v.index in vid:
            continue
        vid[v.index] = len(vid)
        n = v.normal
        slope = 1 - max(0.0, n.z)
        z = v.co.z
        c = mix(SAND, GRASS, (z - 0.15) / 0.35)
        c = mix(c, MOSS, (z - 1.6) / 1.4)
        c = mix(c, ROCK, (slope - 0.45) / 0.25)
        grain = 0.04 * noise.noise(v.co * 4 + off)
        positions.append(v.co.copy())
        normals.append(n.copy())
        colors.append(tuple(max(0, min(1, ch + grain)) for ch in c))
    indices.extend(vid[v.index] for v in f.verts)

scale = max(max(abs(c) for c in p) for p in positions)
pos_q = b''.join(struct.pack('<3h', *(round(c / scale * 32767) for c in p)) for p in positions)
nor_q = b''.join(struct.pack('<3b', *(round(max(-1, min(1, c)) * 127) for c in n)) for n in normals)
col_q = b''.join(struct.pack('<3B', *(round(c * 255) for c in col)) for col in colors)
idx_q = b''.join(struct.pack('<H', i) for i in indices)
assert len(positions) < 65536
b64 = lambda b: base64.b64encode(b).decode('ascii')
with open(args.out, 'w', encoding='utf-8') as out:
    out.write('// Generated by tools/saaristo/blender/island.py (seed %d). Do not edit by hand.\n' % args.seed)
    out.write('export const ISLAND = {scale:%.5f,count:%d,' % (scale, len(positions)))
    out.write('pos:"%s",nor:"%s",col:"%s",idx:"%s"};\n' % (b64(pos_q), b64(nor_q), b64(col_q), b64(idx_q)))
print('island: %d verts, %d tris -> %s' % (len(positions), len(indices) // 3, args.out))
